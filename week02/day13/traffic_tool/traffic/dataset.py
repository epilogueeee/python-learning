class TrafficDataset:
    """一批车辆检测记录"""

    def __init__(self, records: list, errors: list = None): ...

    # 容器协议
    def __len__(self) -> int: ...
    def __getitem__(self, index): ...         # 整数返回记录，切片返回 TrafficDataset
    def __contains__(self, item) -> bool: ...
    def __repr__(self) -> str: ...

    # property
    @property
    def speeds(self) -> list: ...
    @property
    def is_empty(self) -> bool: ...

    # 筛选：全部返回新的 TrafficDataset，支持链式调用
    def filter_by_lane(self, lane: int) -> "TrafficDataset": ...
    def filter_by_type(self, vehicle_type: str) -> "TrafficDataset": ...
    def filter_overspeed(self, limit: float) -> "TrafficDataset": ...
    def filter_by_minute(self, minute: str) -> "TrafficDataset": ...

    # 统计
    def lane_statistics(self) -> dict: ...
    def count_by_type(self) -> dict: ...
    def average_speed_by_type(self) -> dict: ...
    def flow_by_minute(self) -> dict: ...
    def peak_minute(self) -> tuple: ...       # 空数据集返回 (None, 0)